import express from "express";
import cors from "cors";
import helmet from "helmet";
import rateLimit from "express-rate-limit";
import { env } from "@/config/env";
import { assignmentRoutes } from "@/routes/assignment.routes";
import { requirementRoutes } from "@/routes/requirement.routes";
import { draftRoutes } from "@/routes/draft.routes";
import { documentRoutes } from "@/routes/document.routes";
import { analysisRoutes } from "@/routes/analysis.routes";
import { researchRoutes } from "@/routes/research.routes";
import { authRoutes } from "@/routes/auth.routes";
import { assistantRoutes } from "@/routes/assistant.routes";
import { settingsRoutes } from "@/routes/settings.routes";
import { collaborationRoutes } from "@/routes/collaboration.routes";
import { writingRoutes } from "@/routes/writing.routes";
import { errorHandler } from "@/middleware/error.middleware";
import { failure } from "@/utils/apiResponse";

export const app = express();
app.disable("x-powered-by");
app.use(helmet());
app.use(cors({ origin: env.FRONTEND_ORIGIN.split(",").map((value) => value.trim()), credentials: true }));
app.use(express.json({ limit: "2mb" }));
app.use(express.urlencoded({ extended: false, limit: "2mb" }));
const aiLimiter = rateLimit({ windowMs: 60_000, limit: 30, standardHeaders: "draft-7", legacyHeaders: false });
const authLimiter = rateLimit({ windowMs: 15 * 60_000, limit: 10, standardHeaders: "draft-7", legacyHeaders: false });

app.get("/health", (_request, response) => response.json({ ok: true, service: "assignmentos-api" }));
app.get("/api/health", (_request, response) => response.json({ ok: true, service: "assignmentos-api", assistant: env.AI_API_KEY ? "openai" : env.AI_PROVIDER }));
app.use("/api/auth/login", authLimiter);
app.use("/api/auth/register", authLimiter);
app.use("/api/auth", authRoutes);
app.use("/api/assignments", assignmentRoutes);
app.use("/api/requirements", requirementRoutes);
app.use("/api/drafts", draftRoutes);
app.use("/api/documents", documentRoutes);
app.use("/api/analysis", aiLimiter, analysisRoutes);
app.use("/api/research", aiLimiter, researchRoutes);
app.use("/api/assistant", aiLimiter, assistantRoutes);
app.use("/api/writing", aiLimiter, writingRoutes);
app.use("/api/settings", settingsRoutes);
app.use("/api/collaborations", collaborationRoutes);
app.use((_request, response) => failure(response, 404, "API route not found."));
app.use(errorHandler);
